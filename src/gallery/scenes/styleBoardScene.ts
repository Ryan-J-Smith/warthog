import Phaser from 'phaser';
import { SPRITES, SPRITE_RESOLUTION } from '../../assets';
import { riverCrossing } from '../../content/levels';
import { DEPTH, aircraftHeight, shadowAlpha, shadowOffset } from '../../render/layers';
import { SPRITE_SCALE } from '../../render/sprites';
import { TerrainModel, TerrainPainter } from '../../render/terrain';
import { degToRad } from '../../sim/math';
import { BoardWorldScene } from './boardWorldScene';
import { V0_PREFIX, V0_SIZES, VARIANT_B_KEY, addUnit } from './boardStaging';
import type { StagedUnit, UnitKind } from './boardStaging';

/** Gallery-only art: player variant B (generated by scripts/art) and the v0 sprites. */
const PREVIEW_URLS = import.meta.glob<string>('../preview/*.svg', { query: '?url', import: 'default', eager: true });
const V0_URLS = import.meta.glob<string>('../v0/*.svg', { query: '?url', import: 'default', eager: true });

const W = 1920;
const TITLE_H = 40;
const PANEL_Y = 48;
const PANEL_H = 636;
const NEAR = { x: 16, y: PANEL_Y, w: 1150, h: PANEL_H };
const FAR = { x: 1178, y: PANEL_Y, w: 726, h: PANEL_H };
const CARD_Y = 696;
const CARD_H = 372;
/** Presentation zoom for the close-up lineup cards. */
const CARD_ZOOM = 1.5;
/** The v0 desert ground colour, for an honest "before". */
const V0_GROUND = 0xc0b484;

const TAG_STYLE: Phaser.Types.GameObjects.Text.TextStyle = {
  fontFamily: 'system-ui, sans-serif',
  fontStyle: 'bold',
  fontSize: '17px',
  color: '#ffffff',
  backgroundColor: 'rgba(16, 20, 34, 0.82)',
  padding: { x: 8, y: 4 },
};
const NOTE_STYLE: Phaser.Types.GameObjects.Text.TextStyle = {
  fontFamily: 'system-ui, sans-serif',
  fontSize: '14px',
  color: '#ffffff',
  backgroundColor: 'rgba(16, 20, 34, 0.7)',
  padding: { x: 6, y: 3 },
};

/**
 * Art direction v1 style board (`gallery.html?view=board`), for sign-off before the full art pass:
 * - two live terrain panels (zoom 1.0 at Low, zoom 0.45 at High) around the bridge and river,
 *   with enemy + friendly groups drawn exactly as the game draws them;
 * - player variants A (toy A-10) and B (future Warthog), labelled;
 * - enemy / friendly close-up lineups;
 * - a before/after strip against the v0 sprites at their old sizes on the old desert ground.
 * H toggles the ground halos in the live panels.
 */
export class StyleBoardScene extends Phaser.Scene {
  constructor() {
    super('StyleBoard');
  }

  preload(): void {
    const b = PREVIEW_URLS['../preview/a10B.svg'];
    if (b) {
      this.load.svg(VARIANT_B_KEY, b, { width: SPRITES.a10.w * SPRITE_RESOLUTION, height: SPRITES.a10.h * SPRITE_RESOLUTION });
    }
    for (const [path, url] of Object.entries(V0_URLS)) {
      const name = path.slice(path.lastIndexOf('/') + 1).replace(/\.svg$/, '');
      const size = V0_SIZES[name];
      if (!size) continue;
      this.load.svg(`${V0_PREFIX}${name}`, url, { width: size.w * SPRITE_RESOLUTION, height: size.h * SPRITE_RESOLUTION });
    }
  }

  create(): void {
    // Live panels render underneath this scene (it only draws frames, tags and the cards).
    this.scene.add('BoardNear', new BoardWorldScene('BoardNear', { zoom: 1, alt: 0, viewport: NEAR }), true);
    this.scene.add('BoardFar', new BoardWorldScene('BoardFar', { zoom: 0.45, alt: 2, viewport: FAR }), true);
    this.scene.bringToTop();

    this.drawTitle();
    this.drawPanelFrame(NEAR, 'ZOOM 1.0 · LOW', 'Units at true size. Planes at Low.');
    this.drawPanelFrame(FAR, 'ZOOM 0.45 · HIGH', 'Units ×1.3 (as in game). Planes at High.');

    const model = new TerrainModel(riverCrossing);
    const painter = new TerrainPainter(model);
    this.drawPlayerCard(painter, 16, 620);
    this.drawLineupCard(painter, 648, 404, 'ENEMY', [
      { kind: 'tank', x: 90, y: 104, heading: 0, aim: -12 },
      { kind: 'aa', x: 238, y: 100, heading: 0, aim: -20 },
      { kind: 'mech', x: 342, y: 104, heading: 0 },
      { kind: 'truck', x: 86, y: 258, heading: 0 },
      { kind: 'mech', x: 212, y: 262, heading: -30 },
      { kind: 'mech', x: 322, y: 256, heading: 25 },
    ]);
    this.drawLineupCard(painter, 1064, 270, 'FRIENDLY', [
      { kind: 'friendlyTank', x: 92, y: 104, heading: 0, aim: 10 },
      { kind: 'friendlyMech', x: 210, y: 108, heading: 0 },
      { kind: 'friendlyMech', x: 92, y: 256, heading: -25 },
      { kind: 'friendlyMech', x: 210, y: 258, heading: 20 },
    ]);
    this.drawBeforeAfter(painter, 1346, 558);

    const hint = document.getElementById('hint');
    if (hint) hint.textContent = 'H: toggle ground halos · board is 1920×1080';
  }

  private drawTitle(): void {
    this.add.rectangle(0, 0, W, TITLE_H, 0x141a2a).setOrigin(0);
    this.add.text(16, 8, 'WARTHOG · STYLE BOARD v1', { ...TAG_STYLE, fontSize: '20px', backgroundColor: undefined, padding: { x: 0, y: 0 } });
    this.add.text(300, 11, 'chunky toy arcade on lush green countryside · step 1 for approval', {
      fontFamily: 'system-ui, sans-serif',
      fontSize: '16px',
      color: '#b8c4de',
    });
    // Palette chips.
    const chips: Array<[string, number]> = [
      ['grass', 0x68b648],
      ['enemy', 0x86283a],
      ['enemy glow', 0xff5a1e],
      ['friendly', 0xd9e1ea],
      ['friendly blue', 0x2f7df6],
      ['glow', 0x4fe3ff],
      ['road', 0xecd69e],
      ['river', 0x3f9ee4],
      ['roof', 0xe2573f],
    ];
    let x = W - 16;
    for (let i = chips.length - 1; i >= 0; i--) {
      const chip = chips[i];
      if (!chip) continue;
      const label = this.add.text(x, 12, chip[0], { fontFamily: 'system-ui, sans-serif', fontSize: '13px', color: '#b8c4de' }).setOrigin(1, 0);
      x -= label.width + 6;
      this.add.rectangle(x, 11, 18, 18, chip[1]).setOrigin(1, 0).setStrokeStyle(2, 0x000000, 0.6);
      x -= 30;
    }
  }

  private drawPanelFrame(r: { x: number; y: number; w: number; h: number }, title: string, note: string): void {
    this.add.rectangle(r.x, r.y, r.w, r.h).setOrigin(0).setStrokeStyle(3, 0x0b0e18, 1);
    this.add.text(r.x + 10, r.y + 10, title, TAG_STYLE);
    this.add.text(r.x + r.w - 10, r.y + 12, note, NOTE_STYLE).setOrigin(1, 0);
  }

  /** A card with a painted-terrain background (world rect at scale 1) and a title tag. */
  private card(painter: TerrainPainter, key: string, x: number, w: number, world: { x: number; y: number }, title: string): void {
    const tex = this.textures.createCanvas(key, w, CARD_H);
    if (!tex) throw new Error(`Could not create ${key}`);
    painter.paint(tex.getContext(), world.x, world.y, w, CARD_H, 1, 'near');
    tex.refresh();
    this.add.image(x, CARD_Y, key).setOrigin(0).setDepth(-1);
    this.add.rectangle(x, CARD_Y, w, CARD_H).setOrigin(0).setStrokeStyle(3, 0x0b0e18, 1);
    this.add.text(x + 8, CARD_Y + 8, title, TAG_STYLE).setDepth(DEPTH.worldUi);
  }

  private drawPlayerCard(painter: TerrainPainter, x: number, w: number): void {
    this.card(painter, 'board-card-player', x, w, { x: 5240, y: 3040 }, 'PLAYER · pick A or B  (×1.5)');
    const height = aircraftHeight(0);
    const off = shadowOffset(height);
    const planes: Array<[string, number, string, string]> = [
      ['a10', x + 160, 'A · toy A-10', 'fat body, shark mouth, huge GAU-8'],
      [VARIANT_B_KEY, x + 460, 'B · future Warthog', 'rail cannon, canards, glowing pods'],
    ];
    for (const [key, cx, label, note] of planes) {
      const cy = CARD_Y + 190;
      const rot = degToRad(-90);
      this.add
        .image(cx + off.x * CARD_ZOOM, cy + off.y * CARD_ZOOM, key)
        .setTintFill(0x000000)
        .setAlpha(shadowAlpha(height))
        .setScale(SPRITE_SCALE * CARD_ZOOM)
        .setRotation(rot);
      this.add.image(cx, cy, key).setScale(SPRITE_SCALE * CARD_ZOOM).setRotation(rot);
      this.add.text(cx, CARD_Y + CARD_H - 50, label, { ...TAG_STYLE, fontSize: '18px' }).setOrigin(0.5, 0);
      this.add.text(cx, CARD_Y + CARD_H - 22, note, NOTE_STYLE).setOrigin(0.5, 0);
    }
  }

  private drawLineupCard(painter: TerrainPainter, x: number, w: number, title: string, units: StagedUnit[]): void {
    this.card(painter, `board-card-${title}`, x, w, { x: 5600 - w / 2, y: 3150 }, `${title}  (×1.5)`);
    for (const u of units) addUnit(this, { ...u, x: x + u.x, y: CARD_Y + u.y }, { extraScale: CARD_ZOOM });
  }

  private drawBeforeAfter(painter: TerrainPainter, x: number, w: number): void {
    this.card(painter, 'board-card-ba', x, w, { x: 5300, y: 3150 }, 'BEFORE (v0) → AFTER (v1)  ·  true size, zoom 1.0');
    const half = Math.floor(w * 0.42);
    // Left: the old desert ground and v0 sprites at their old native sizes.
    this.add.rectangle(x + 2, CARD_Y + 2, half - 2, CARD_H - 4, V0_GROUND).setOrigin(0).setDepth(-0.5);
    this.add.rectangle(x + half, CARD_Y, 3, CARD_H, 0x0b0e18).setOrigin(0);
    const before = (u: Omit<StagedUnit, 'heading'> & { heading?: number }): void => {
      addUnit(this, { heading: 0, ...u }, { v0: true });
    };
    const after = (u: Omit<StagedUnit, 'heading'> & { heading?: number }): void => {
      addUnit(this, { heading: 0, ...u });
    };
    const b = (dx: number, dy: number): { x: number; y: number } => ({ x: x + dx, y: CARD_Y + dy });
    const a = (dx: number, dy: number): { x: number; y: number } => ({ x: x + half + dx, y: CARD_Y + dy });
    const kinds: UnitKind[] = ['tank', 'aa', 'truck', 'mech', 'friendlyTank', 'friendlyMech'];

    this.add.image(b(118, 0).x, b(0, 118).y, `${V0_PREFIX}a10`).setScale(SPRITE_SCALE).setRotation(degToRad(-90));
    kinds.forEach((kind, i) => before({ kind, ...b(40 + (i % 3) * 78, 222 + Math.floor(i / 3) * 70) }));
    this.add.image(a(160, 0).x, a(0, 128).y, 'a10').setScale(SPRITE_SCALE).setRotation(degToRad(-90));
    kinds.forEach((kind, i) => after({ kind, ...a(52 + (i % 3) * 104, 250 + Math.floor(i / 3) * 76) }));
    this.add.text(x + 8, CARD_Y + CARD_H - 30, 'v0: olive, realistic scale', NOTE_STYLE);
    this.add.text(x + half + 8, CARD_Y + CARD_H - 30, 'v1: toy scale ≈2×, team colours', NOTE_STYLE);
  }
}
